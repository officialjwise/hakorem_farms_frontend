#!/usr/bin/env bash
# Pulls the backend's contract across and regenerates the client (ADR 0018, amended F6).
#
#   ./scripts/sync-contract.sh                copy ../backend/contract/openapi.yaml, regenerate, typecheck
#   ./scripts/sync-contract.sh --github [ref] fetch contract/openapi.yaml and docs/CONTRACT_CHANGELOG.md
#                                             from the public backend repository at one commit (ref is a
#                                             branch, a tag or a commit; default main), regenerate,
#                                             typecheck. Needs no sibling clone, so cloud sessions use it.
#   ./scripts/sync-contract.sh --check        CI: fail if contract/openapi.yaml was edited by hand or the
#                                             committed client differs from it, then typecheck. Offline.
#
# Every sync writes a header of YAML comments at the top of contract/openapi.yaml: where the contract
# came from (the commit, for --github), and the sha256 of every byte below the header. --check
# recomputes that digest, so a hand edit to the contract fails CI.
#
# The upstream files land in .contract-upstream/ (gitignored): the contract as published, and the
# changelog to read after a sync.
#
# It fails loudly (non-zero exit, a message that says what to do) when the source is missing, when the
# fetch fails, when the contract was hand-edited, when the generated client is stale, or when an app
# no longer compiles against the contract.
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.."

readonly repo="officialjwise/hakorem_farms_backend"
readonly sibling_file="../backend/contract/openapi.yaml"
readonly target_file="contract/openapi.yaml"
readonly upstream_dir=".contract-upstream"
readonly header_mark="# hakorem-contract-sync:"

usage() {
  echo "usage: ./scripts/sync-contract.sh [--check | --github [ref]]" >&2
  exit 2
}

mode="sync"
ref=""
case "${1:-}" in
  "") ;;
  --check) mode="check"; [[ $# -eq 1 ]] || usage ;;
  --github) mode="github"; ref="${2:-main}"; [[ $# -le 2 ]] || usage ;;
  *) usage ;;
esac

sha256_of() { sha256sum "$1" | cut -d' ' -f1; }

# Prints the contract below the three header lines, byte for byte (the whole file when it has none).
body_of() {
  if head -n1 "$1" | grep -q "^${header_mark}"; then tail -n +4 "$1"; else cat "$1"; fi
}

# Writes target_file as the header followed by the upstream bytes, unchanged.
write_with_header() {
  local upstream="$1" source="$2" digest
  digest="$(sha256_of "$upstream")"
  {
    echo "${header_mark} GENERATED by scripts/sync-contract.sh. Never edit this file; run pnpm sync-contract."
    echo "${header_mark} source ${source}"
    echo "${header_mark} sha256 ${digest}"
    cat "$upstream"
  } >"$target_file.tmp"
  if [[ -f "$target_file" ]] && cmp -s "$target_file.tmp" "$target_file"; then
    rm "$target_file.tmp"
    echo "sync-contract: contract/openapi.yaml already matches ${source}."
  else
    mv "$target_file.tmp" "$target_file"
    echo "sync-contract: wrote contract/openapi.yaml from ${source}."
  fi
}

case "$mode" in
  sync)
    if [[ ! -f "$sibling_file" ]]; then
      echo "sync-contract: $sibling_file does not exist. Open the workspace root so ../backend is beside frontend/, or run ./scripts/sync-contract.sh --github." >&2
      exit 1
    fi
    source="../backend (working tree)"
    if sibling_sha="$(git -C ../backend rev-parse HEAD 2>/dev/null)"; then
      if git -C ../backend diff --quiet HEAD -- contract/openapi.yaml 2>/dev/null; then
        source="github:${repo}@${sibling_sha} contract/openapi.yaml (via ../backend)"
      else
        source="../backend at ${sibling_sha} with uncommitted changes to contract/openapi.yaml"
      fi
    fi
    write_with_header "$sibling_file" "$source"
    echo "sync-contract: read ../backend/docs/CONTRACT_CHANGELOG.md for what changed."
    pnpm --filter @hakorem/api-client generate
    ;;

  github)
    if [[ "$ref" =~ ^[0-9a-f]{40}$ ]]; then
      sha="$ref"
    else
      # The anonymous git lane answers this without credentials or the GitHub API.
      # An annotated tag lists its commit on the peeled (^{}) line, so that line wins.
      refs="$(git ls-remote "https://github.com/${repo}" "refs/heads/$ref" "refs/tags/$ref" "refs/tags/$ref^{}")"
      sha="$( (grep '\^{}$' <<<"$refs" || head -n1 <<<"$refs") | head -n1 | cut -f1)"
      if [[ ! "$sha" =~ ^[0-9a-f]{40}$ ]]; then
        echo "sync-contract: could not resolve '$ref' in ${repo}. Pass a branch, a tag or a full 40-character commit." >&2
        exit 1
      fi
    fi
    mkdir -p "$upstream_dir"
    raw="https://raw.githubusercontent.com/${repo}/${sha}"
    for pair in "contract/openapi.yaml:openapi.yaml" "docs/CONTRACT_CHANGELOG.md:CONTRACT_CHANGELOG.md"; do
      if ! curl --silent --show-error --fail --retry 3 --output "$upstream_dir/${pair#*:}.part" "$raw/${pair%%:*}"; then
        echo "sync-contract: could not fetch ${pair%%:*} at ${sha}. Nothing was changed." >&2
        rm -f "$upstream_dir"/*.part
        exit 1
      fi
    done
    for name in openapi.yaml CONTRACT_CHANGELOG.md; do mv "$upstream_dir/$name.part" "$upstream_dir/$name"; done
    echo "$sha" >"$upstream_dir/COMMIT"
    write_with_header "$upstream_dir/openapi.yaml" "github:${repo}@${sha} contract/openapi.yaml"
    echo "sync-contract: read ${upstream_dir}/CONTRACT_CHANGELOG.md (at ${sha:0:7}) for what changed."
    pnpm --filter @hakorem/api-client generate
    ;;

  check)
    recorded="$(grep -m1 "^${header_mark} sha256 " "$target_file" | awk '{print $4}' || true)"
    if [[ -z "$recorded" ]]; then
      echo "sync-contract: contract/openapi.yaml has no sync header. Run ./scripts/sync-contract.sh --github and commit the result." >&2
      exit 1
    fi
    actual="$(body_of "$target_file" | sha256sum | cut -d' ' -f1)"
    if [[ "$actual" != "$recorded" ]]; then
      echo "sync-contract: contract/openapi.yaml was edited after it was synced (sha256 $actual, header says $recorded). Never hand-edit it; run ./scripts/sync-contract.sh --github." >&2
      exit 1
    fi
    if [[ -f "$sibling_file" ]] && ! cmp -s <(body_of "$target_file") "$sibling_file"; then
      echo "sync-contract: note: contract/openapi.yaml differs from ../backend/contract/openapi.yaml. Run without --check to take the backend's." >&2
    fi
    pnpm --filter @hakorem/api-client generate:check
    ;;
esac

# The gate that matters: every package and app still compiles against the regenerated types.
if ! pnpm typecheck; then
  echo "sync-contract: FAILED. An app no longer compiles against the contract. Fix the type errors; never pin to an old contract." >&2
  exit 1
fi

echo "sync-contract: ok."
